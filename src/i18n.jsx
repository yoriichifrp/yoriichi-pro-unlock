const LanguageContext = createContext(null);
const STORAGE_KEY = 'ypu.lang';

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const stored = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null;
    return stored === 'en' || stored === 'es' ? stored : 'es';
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* almacenamiento no disponible */
    }
  }, [lang]);

  const setLang = useCallback((next) => {
    if (next === 'es' || next === 'en') setLangState(next);
  }, []);

  const value = useMemo(() => {
    const t = (key) => {
      const entry = DICT[lang]?.[key];
      if (entry !== undefined) return entry;
      const fallback = DICT.es[key];
      return fallback !== undefined ? fallback : key;
    };
    const bi = (record, field) => {
      if (!record) return '';
      const primary = record[`${field}_${lang}`];
      if (primary) return primary;
      const alt = record[`${field}_${lang === 'es' ? 'en' : 'es'}`];
      return alt || '';
    };
    const err = (code) => t(`error.${code || 'generic'}`);
    return { lang, setLang, t, bi, err };
  }, [lang, setLang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useI18n debe usarse dentro de LanguageProvider');
  return context;
}
